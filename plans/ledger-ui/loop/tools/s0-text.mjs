import {Window} from "happy-dom";
import {readFileSync} from "node:fs";
const html=readFileSync(process.argv[2],"utf8"),m=html.match(/<script>([\s\S]*)<\/script>/);
const win=new Window({url:"https://localhost/",console:{log(){},warn(){},info(){},debug(){},error(){}}});
win.document.write(html.replace(m[0],""));await win.happyDOM.waitUntilComplete();win.eval(m[1]);
const d=win.document,n=s=>(s||"").replace(/\s+/g," ").trim(),all=s=>[...d.querySelectorAll(s)];
const out={};
out.brand=n(d.querySelector(".top")?.firstElementChild?.textContent);
out.tabs=all(".tab").map(t=>({p:t.dataset.p,label:n([...t.childNodes].filter(c=>c.nodeType===3||!c.classList?.contains("badge")).map(c=>c.textContent).join("")),badge:n(t.querySelector(".badge")?.textContent)}));
out.switcherButton=n(d.querySelector("#sw").textContent);
d.querySelector("#sw").click();
out.switcherItems=all("#sp [data-sc], #sp button, #sp a").map(x=>({sc:x.dataset.sc,text:n(x.textContent)}));
d.querySelector("#pb").click();
out.periodButton=n(d.querySelector("#pb").textContent);
out.periodItems=all("#pp button, #pp label").map(x=>n(x.textContent)).filter(Boolean);
d.querySelector("#pprev").click();out.afterPrev=n(d.querySelector("#pb").textContent);
d.querySelector("#pnext").click();d.querySelector("#pnext").click();out.afterNextNext=n(d.querySelector("#pb").textContent);
d.querySelector("#hb").click();out.help=all("#hp a, #hp button").map(x=>n(x.textContent));
out.gb=n(d.querySelector("#gb")?.getAttribute("aria-label")||d.querySelector("#gb")?.title);
console.log(JSON.stringify(out,null,1));
