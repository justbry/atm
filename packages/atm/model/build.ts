#!/usr/bin/env bun
/**
 * Regenerates `model/generated/` from the ledger model (`model/ledger.v1.json`, resolved against `kpis/school.v1.json`):
 * the KPI catalog, the disclosure class table, the KPI document's OpenAPI components and the JSON-LD context
 * (`src/model/generate.ts`). With `--check` it writes nothing and exits 1 naming each file that is stale, hand-edited,
 * missing or not generated; the comparison is of bytes (the generator writes what Biome's formatter keeps).
 * Usage: bun model/build.ts [--check]
 */
import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	writeFileSync,
} from "node:fs";
import { basename, dirname, join } from "node:path";
import {
	generatedDirectory,
	generateModelFiles,
} from "../src/model/generate.js";
import { LEDGER_MODEL } from "../src/model/ledger-model.js";

const packageRoot = join(import.meta.dir, "..");
const check = process.argv.includes("--check");
const files = generateModelFiles(LEDGER_MODEL);

const differing: string[] = [];
for (const file of files) {
	const target = join(packageRoot, file.path);
	const current = existsSync(target) ? readFileSync(target, "utf8") : null;
	if (current === file.content) continue;
	differing.push(`${file.path}${current === null ? " (missing)" : ""}`);
	if (check) continue;
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, file.content);
}
const expected = new Set(files.map((file) => basename(file.path)));
const directory = join(packageRoot, generatedDirectory);
const strays = (existsSync(directory) ? readdirSync(directory) : [])
	.filter((name) => !expected.has(name))
	.map((name) => `${generatedDirectory}/${name}`);

if (check) {
	const problems = [
		...differing.map((path) => `${path}: stale or hand-edited`),
		...strays.map((path) => `${path}: not generated by model/build.ts`),
	];
	if (problems.length > 0) {
		process.stderr.write(
			`${problems.join("\n")}\nRun \`bun model/build.ts\` to regenerate.\n`,
		);
		process.exit(1);
	}
	process.stdout.write(`${files.length} generated files are current\n`);
} else {
	process.stdout.write(
		differing.length > 0
			? `wrote ${differing.join(", ")}\n`
			: `${files.length} generated files are current\n`,
	);
	for (const path of strays)
		process.stderr.write(`${path}: not generated by model/build.ts\n`);
}
