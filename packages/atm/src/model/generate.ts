// ---- JSON as Biome writes it: tabs, every non-empty object expanded, an array of scalars on one line when it fits
const lineWidth = 80;
const tabColumns = 2;
const isScalar = (value: unknown): boolean =>
	value === null || typeof value !== "object";
const writeJson = (
	value: unknown,
	depth: number,
	before: string,
	after: string,
): string => {
	if (isScalar(value)) return JSON.stringify(value);
	const indent = "\t".repeat(depth + 1);
	const close = "\t".repeat(depth);
	if (Array.isArray(value)) {
		if (value.length === 0) return "[]";
		if (value.every(isScalar)) {
			const flat = `[${value.map((item) => JSON.stringify(item)).join(", ")}]`;
			if (
				depth * tabColumns + before.length + flat.length + after.length <=
				lineWidth
			)
				return flat;
		}
		const items = value.map(
			(item, index) =>
				`${indent}${writeJson(item, depth + 1, "", index < value.length - 1 ? "," : "")}`,
		);
		return `[\n${items.join(",\n")}\n${close}]`;
	}
	const entries = Object.entries(value as Record<string, unknown>).filter(
		([, item]) => item !== undefined,
	);
	if (entries.length === 0) return "{}";
	const lines = entries.map(([key, item], index) => {
		const label = `${JSON.stringify(key)}: `;
		return `${indent}${label}${writeJson(item, depth + 1, label, index < entries.length - 1 ? "," : "")}`;
	});
	return `{\n${lines.join(",\n")}\n${close}}`;
};
/** JSON in the bytes Biome's formatter (`biome.json`: tabs, width 80) keeps. */
export const biomeJson = (value: unknown): string =>
	`${writeJson(value, 0, "", "")}\n`;

// ---- The model facts the outputs share
const kindOfUnit: Record<KpiUnit, KpiCatalogKind> = {
	cents: "money",
	count: "count",
	ratio: "rate",
};
/** The disclosure classes in the schema's order (the disclosure file's `classes` keys). */
const classOrder = modelSchema.$defs.measure.properties.disclosure.properties
	.class.enum as ResolvedMeasure["disclosure"]["class"][];
const formats = modelSchema.$defs.measure.properties.format.enum;
const detailSteps = modelSchema.$defs.dimension.properties.need.enum;

/** The measures the KPI document carries, in its order: by `document.position`, then the rest in model order. */
export const documentMeasures = (
	measures: readonly ResolvedMeasure[],
): ResolvedMeasure[] =>
	measures
		.map((measure, index) => ({ measure, index }))
		.filter(({ measure }) => measure.document)
		.sort(
			(first, second) =>
				(first.measure.document?.position ?? Number.POSITIVE_INFINITY) -
					(second.measure.document?.position ?? Number.POSITIVE_INFINITY) ||
				first.index - second.index,
		)
		.map(({ measure }) => measure);

const dimensionOf = (
	model: LedgerModel,
	measure: ResolvedMeasure,
): ModelDimension | undefined =>
	model.dimensions.find((dimension) => dimension.id === measure.dimensions[0]);
/** `id`, or `id:*` for a measure split by a dimension (the document expands it per value). */
export const catalogKey = (measure: ResolvedMeasure): string =>
	measure.dimensions.length > 0 ? `${measure.id}:*` : measure.id;
const isDerived = (measure: ResolvedMeasure): boolean =>
	measure.kpi?.compute.op === "ratio" || measure.kpi?.compute.op === "combine";

// ---- kpi-catalog.v1.json
export const kpiCatalogOf = ({
	model,
	measures,
}: ResolvedModel): Record<string, KpiCatalogEntry> => {
	const catalog: Record<string, KpiCatalogEntry> = {};
	for (const measure of documentMeasures(measures)) {
		const dimensionNeed = dimensionOf(model, measure)?.need;
		const need =
			measure.document?.need ??
			(dimensionNeed && dimensionNeed !== "total" ? dimensionNeed : undefined);
		catalog[catalogKey(measure)] = {
			title: measure.document?.title ?? measure.title,
			kind: kindOfUnit[measure.unit],
			ruleOf: measure.disclosure.ruleOf ?? measure.id,
			...(need ? { need } : {}),
			...(measure.inputs.length > 0 ? { inputs: [...measure.inputs] } : {}),
			format: measure.format,
		};
	}
	return catalog;
};
export const derivedKpisOf = ({
	measures,
}: ResolvedModel): Record<string, DerivedKpi> =>
	Object.fromEntries(
		measures.filter(isDerived).map((measure) => [
			measure.id,
			{
				inputs: [...measure.inputs],
				capped: measure.disclosure.capped ?? false,
			},
		]),
	);

// ---- disclosure-classes.v1.json
/** The disclosure file's class table: each class's spec KPIs, in model (spec) order. */
export const disclosureClassesOf = ({
	measures,
}: ResolvedModel): Record<string, string[]> =>
	Object.fromEntries(
		classOrder.map((kpiClass) => [
			kpiClass,
			measures
				.filter(
					(measure) =>
						measure.source === "kpiSpec" &&
						measure.disclosure.class === kpiClass,
				)
				.map((measure) => measure.id),
		]),
	);

