/**
 * What `bun model/build.ts` writes from the ledger model (`model/ledger.v1.json`) into `model/generated/`: the KPI
 * document's catalog and the derived KPIs (read by the Worker through `src/ledger/kpi-catalog.ts`), the disclosure
 * file's class table, the OpenAPI components of the KPI document and the model's JSON-LD context. Pure: the resolved
 * model in, `{ path, content }` out. Each content is the bytes Biome's JSON formatter leaves as they are (objects
 * expanded, a flat array on one line when it fits in 80 columns), so `--check` compares bytes. Not Worker code.
 */
