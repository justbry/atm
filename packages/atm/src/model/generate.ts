const schemaRef = (name: string): { $ref: string } => ({
	$ref: `#/components/schemas/${name}`,
});
const pascalCase = (id: string): string =>
	id
		.split("_")
		.map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
		.join("");
const escapeRegex = (text: string): string =>
	text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const captureGroup = /\((?!\?)([^()]*)\)/;
/** A value of the dimension: its closed list, else what its entity's key pattern captures, else anything. */
const dimensionValuePattern = (
	model: LedgerModel,
	dimension: ModelDimension,
): string => {
	if (dimension.values)
		return `(?:${dimension.values.map(escapeRegex).join("|")})`;
	const keyPattern = model.entities.find(
		(entity) => entity.id === dimension.entity,
	)?.key?.pattern;
	const captured = keyPattern ? captureGroup.exec(keyPattern)?.[1] : undefined;
	return captured ? `(?:${captured})` : ".+";
};
/** A model IRI as an `atm:` CURIE. */
const atmCurie = (model: LedgerModel, iri: string): string => {
	if (!iri.startsWith(model.namespace))
		throw new Error(`${iri} is not under ${model.namespace}`);
	return `atm:${iri.slice(model.namespace.length)}`;
};
/** The CURIE of an entity, checked to name one. */
const entityCurie = (model: LedgerModel, id: string): string => {
	if (!model.entities.some((entity) => entity.id === id))
		throw new Error(`${id} is not an entity of ${model.id}`);
	return atmCurie(model, termIri.entity(model, id));
};

