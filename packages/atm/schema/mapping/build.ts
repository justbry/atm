#!/usr/bin/env bun
/**
 * Writes schema/mapping/index.ts from the mapping files: one static JSON import per file, so the built library carries
 * them. Run after adding or changing a mapping file: `bun schema/mapping/build.ts`. The drift test fails until you do.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const here = import.meta.dir;

/** The mapping files in this directory, sorted, so the generated index is the same on every machine. */
export function mappingFileNames(dir: string = here): string[] {
	return readdirSync(dir)
		.filter((f) => /^stripe\.[a-z_.]+\.v\d+\.json$/.test(f))
		.sort();
}

/** The text of index.ts for these mapping file names. Pure: the drift test calls it without writing anything. */
export function renderIndex(files: string[]): string {
	const imports = files.map((f, i) => `import m${i} from "./${f}";`);
	return [
		"// Generated by `bun schema/mapping/build.ts` from the mapping files in this directory. Do not edit.",
		...imports,
		"",
		"/** Every mapping file, in filename order. */",
		`export const MAPPING_FILES: readonly unknown[] = [${files.map((_, i) => `m${i}`).join(", ")}];`,
		"",
	].join("\n");
}

if (import.meta.main) {
	writeFileSync(join(here, "index.ts"), renderIndex(mappingFileNames()));
	console.log(
		`wrote schema/mapping/index.ts (${mappingFileNames().length} mappings)`,
	);
}
